// [{ slug, zone, name, img }] เรียงตามห้อง
const SAMPLES = ZONES.flatMap(([slug, zone]) =>
  (CATALOG[slug] || []).map(([file, name]) => ({ slug, zone, name, img: site(`img/products/${slug}/${file}.jpg`) })),
);

// การ์ดสินค้าตัวอย่าง (หน้าตาเดียวกับ productCard แต่ไม่มีราคา ปุ่มตะกร้า และรายการโปรด)
function sampleCard(s) {
  return `<article class="card sample z-${s.slug}">
<div class="img"><img src="${esc(s.img)}" alt="${esc(s.name)}" loading="lazy"></div>
<span class="zone">${esc(s.zone)}</span>
<span class="name">${esc(s.name)}</span>
<div class="foot"><span class="soon">เร็วๆ นี้</span></div>
</article>`;
}

// ตัวอย่างที่ชื่อไม่ซ้ำกับสินค้าจริงใน list
function samplesExcept(list) {
  const names = new Set(list.map((p) => p.name.trim()));
  return SAMPLES.filter((s) => !names.has(s.name));
}
